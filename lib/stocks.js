const STOCKS = [];
for (const market of Object.keys(RAW)) {
  for (const row of RAW[market]) STOCKS.push({ code: row[0], name: row[1], market });
}

const MARKET_LABEL = { sh: '沪市', sz: '深市', hk: '港股', us: '美股' };

function yahooSymbol(s) {
  if (s.market === 'sh') return s.code + '.SS';
  if (s.market === 'sz') return s.code + '.SZ';
  if (s.market === 'hk') return s.code + '.HK';
  return s.code;
}
function tencentSymbol(s) {
  return s.market + s.code;
}
function search(q, market) {
  q = (q || '').trim().toLowerCase();
  return STOCKS.filter((s) => {
    if (market && s.market !== market) return false;
    if (!q) return true;
    return s.code.toLowerCase().includes(q) || s.name.toLowerCase().includes(q);
  });
}
function findBySymbol(symbol) {
  return STOCKS.find((s) => yahooSymbol(s) === symbol) || null;
}
function findIndex(symbol) {
  return INDICES.find((i) => i.symbol === symbol) || null;
}

module.exports = { STOCKS, INDICES, MARKET_LABEL, yahooSymbol, tencentSymbol, search, findBySymbol, findIndex };
